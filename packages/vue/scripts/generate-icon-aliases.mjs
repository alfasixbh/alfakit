// Writes src/lib/icon-aliases.ts: legacy Lucide names (`filter`, `trash-2`, `home`, …) that
// @lucide/vue only exports from its index, mapped to the icon file that ships them.
// Run after updating @lucide/vue: `node scripts/generate-icon-aliases.mjs`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'node_modules/@lucide/vue/dist/esm')
const index = readFileSync(join(dist, 'lucide-vue.mjs'), 'utf8')
const files = new Set(
    readdirSync(join(dist, 'icons'))
        .filter((file) => file.endsWith('.mjs'))
        .map((file) => file.slice(0, -4)),
)

const kebab = (name) =>
    name
        .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
        .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
        .replace(/([a-zA-Z])(\d)/g, '$1-$2')
        .toLowerCase()

const aliases = {}

for (const [, names, file] of index.matchAll(
    /export \{([^}]*)\} from '\.\/icons\/([^']+)\.mjs'/g,
)) {
    for (const [, name] of names.matchAll(/default as (\w+)/g)) {
        if (name.endsWith('Icon') || name.startsWith('Lucide')) continue

        const alias = kebab(name)

        // `Grid2x2` would read as `grid-2x-2`; those names already ship as files (`grid-2x2`).
        if (alias !== file && !files.has(alias) && !/\dx-\d/.test(alias)) aliases[alias] = file
    }
}

const entries = Object.keys(aliases)
    .sort()
    .map((alias) => `  '${alias}': '${aliases[alias]}',`)
    .join('\n')

writeFileSync(
    join(root, 'src/lib/icon-aliases.ts'),
    `// Generated by scripts/generate-icon-aliases.mjs. Do not edit.\n\n/** Legacy Lucide names that @lucide/vue ships under another file name. */\nexport const iconAliases: Record<string, string> = {\n${entries}\n}\n`,
)

console.log(`icon-aliases.ts: ${Object.keys(aliases).length} aliases`)
