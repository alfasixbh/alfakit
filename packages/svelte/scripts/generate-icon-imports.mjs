// Writes src/lib/icon-imports.ts: a lazy import for every Lucide icon (aliases included),
// the Svelte counterpart of `lucide-react/dynamic`. Run after upgrading @lucide/svelte:
//   node scripts/generate-icon-imports.mjs
import { readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const icons = join(realpathSync(join(root, 'node_modules', '@lucide', 'svelte')), 'dist', 'icons')

const names = readdirSync(icons)
    .filter((file) => file.endsWith('.js') && file !== 'index.js')
    .map((file) => file.slice(0, -'.js'.length))
    .sort()

const lines = names.map((name) => `  '${name}': () => import('@lucide/svelte/icons/${name}'),`)

writeFileSync(
    join(root, 'src', 'lib', 'icon-imports.ts'),
    `// Generated by scripts/generate-icon-imports.mjs. Do not edit.
import type { LucideIcon } from '@lucide/svelte'

type IconModule = Promise<{ default: LucideIcon }>

/** Lazy imports of every Lucide icon by kebab-case name; each icon is its own chunk. */
export const iconImports: Record<string, () => IconModule> = {
${lines.join('\n')}
}
`,
)

console.log(`Wrote ${names.length} icon imports.`)
