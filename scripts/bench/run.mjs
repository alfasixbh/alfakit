#!/usr/bin/env node
/**
 * AlfaKit benchmark suite: the React, Vue and Svelte playgrounds (and the Filament v5 app in
 * benchmarks/filament-app when it is served) on five scenarios — a table of 50 and of 500 rows
 * with filters, a form with 100 fields and a repeater, a dashboard with six widgets, and global
 * search. For each it measures, over HTTP, the server response time and payload of the page and
 * of the request behind the interaction, and, in Chrome through Playwright, time to interactive,
 * total blocking time, DOM size and interaction latency. Medians of N runs after warm-up; the
 * hardware and server software are recorded with the results.
 *
 *   pnpm bench                                  every target that answers, 7 runs, 2 warm-ups
 *   pnpm bench --runs 15 --warmup 3 --label m5  more runs, a name for the results file
 *   pnpm bench --targets react,filament         some targets only (react, vue, svelte, filament)
 *   pnpm bench --scenarios list-50,form         some scenarios only (list-50, list-500, form, dashboard, search)
 *   pnpm bench --no-browser                     server measurements only
 *   pnpm bench --keep-debug                     leave APP_DEBUG as it is (see below)
 *   pnpm bench --caches none                    Laravel caches: optimize (default), none or keep
 *   pnpm bench --ssr                            leave Inertia SSR as each app configures it
 *   pnpm bench --update-docs                    also write the tables into docs/content/getting-started/performance.md
 *   pnpm bench:docs                             rewrite the docs tables from benchmarks/results/suite/latest.json
 *
 * Before measuring, APP_DEBUG is set to false in each target's .env (and restored afterwards,
 * also on Ctrl+C) so no target pays for debug tooling (AlfaKit's debug panel is on whenever
 * APP_DEBUG is), and Inertia's devtools (on in the `local` environment) are switched off, as is
 * Inertia SSR unless --ssr (no SSR server runs, and Inertia would try to reach one per page).
 * Every app gets the same Laravel caches: `php artisan optimize` (config, events, routes, views
 * and `alfakit:optimize` / `filament:optimize`) before the run, put back afterwards. Seed the data first: `php artisan db:seed --class="Database\Seeders\Benchmark\BenchmarkSeeder"`
 * in each app (see benchmarks/README.md). Results: benchmarks/results/suite/<date>-<label>.json,
 * latest.json and latest.md.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
    browserVersion,
    launchBrowser,
    measureInteraction,
    measurePageLoad,
    signedInContext,
} from './lib/browser.mjs'
import { cacheGuard } from './lib/caches.mjs'
import { debugOffGuard } from './lib/env.mjs'
import { hardware } from './lib/hardware.mjs'
import { fullMarkdown } from './lib/report.mjs'
import { requestsFor, serverInfo, signIn } from './lib/server.mjs'
import { summarize } from './lib/stats.mjs'
import { SCENARIOS, SEARCH_RESULT, SEARCH_TERM, SELECTORS, TARGETS } from './targets.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../..')
const resultsDir = join(root, 'benchmarks/results/suite')
const docsPage = join(root, 'docs/content/getting-started/performance.md')

const args = process.argv.slice(2)
const option = (name, fallback) => {
    const index = args.indexOf(`--${name}`)

    return index === -1 ? fallback : args[index + 1]
}
const flag = (name) => args.includes(`--${name}`)
const list = (name) =>
    option(name, null)
        ?.split(',')
        .map((value) => value.trim())
        .filter(Boolean) ?? null

const RUNS = Number(option('runs', 7))
const WARMUP = Number(option('warmup', 2))
const LABEL = option('label', 'local')

// ------------------------------------------------------------------ Docs only

function writeDocs(results) {
    const start = '<!-- bench:results:start -->'
    const end = '<!-- bench:results:end -->'
    const page = readFileSync(docsPage, 'utf8')

    if (!page.includes(start) || !page.includes(end))
        throw new Error(`${docsPage} has no ${start} … ${end} block`)

    const body = [
        start,
        '',
        `<!-- Generated by \`pnpm bench --update-docs\` / \`pnpm bench:docs\` from benchmarks/results/suite/${results.meta.file}. Do not edit by hand. -->`,
        '',
        fullMarkdown(results),
        '\\* **Results vary by hardware**, configuration, data and versions, and between runs on the same machine; compare the columns of one run, not numbers from different machines, and run `pnpm bench` yourself.',
        '',
        end,
    ].join('\n')

    writeFileSync(
        docsPage,
        page.slice(0, page.indexOf(start)) + body + page.slice(page.indexOf(end) + end.length),
    )

    // Keep the page in the repository's format (tables aligned by Prettier) when it is installed.
    const prettier = join(root, 'node_modules/.bin/prettier')

    if (existsSync(prettier))
        spawnSync(prettier, ['--write', docsPage], { cwd: root, stdio: 'ignore' })

    console.log(`Updated ${docsPage}`)
}

if (flag('docs-only')) {
    const latest = join(resultsDir, 'latest.json')

    if (!existsSync(latest)) throw new Error(`No results yet: run pnpm bench first (${latest})`)

    writeDocs(JSON.parse(readFileSync(latest, 'utf8')))
    process.exit(0)
}

// ------------------------------------------------------------------ Targets and APP_DEBUG

const wantedTargets = list('targets')
const wantedScenarios = list('scenarios')
const scenarios = SCENARIOS.filter(
    (scenario) => !wantedScenarios || wantedScenarios.includes(scenario.id),
)
const candidates = TARGETS.filter((target) => !wantedTargets || wantedTargets.includes(target.name))
const CACHES = option('caches', 'optimize')

if (!['optimize', 'none', 'keep'].includes(CACHES)) throw new Error(`--caches ${CACHES}?`)

const caches = cacheGuard(root, CACHES)
const envGuard = debugOffGuard(root, { keepDebug: flag('keep-debug'), ssr: flag('ssr') })
const restoreEnv = envGuard.restore
const disableDebug = envGuard.disable

// ------------------------------------------------------------------ Run

const meta = {
    date: new Date().toISOString(),
    label: LABEL,
    runs: RUNS,
    warmup: WARMUP,
    caches: CACHES,
    hardware: hardware(),
    // Other work on the machine skews timings; the 1/5/15-minute load averages bracket the run.
    loadAverage: { start: os.loadavg().map((value) => Math.round(value * 100) / 100), end: null },
    browser: null,
    searchTerm: SEARCH_TERM,
    searchResult: SEARCH_RESULT,
    scenarios: scenarios.map(({ id, label, path, interaction, interactionLabel }) => ({
        id,
        label,
        path,
        interaction,
        interactionLabel,
    })),
    targets: [],
    notes: [
        'Server times are measured over loopback with one sequential client (TTFB for pages, full response time for interaction requests).',
        'Time to interactive is when the page is usable (rows rendered, 100 fields mounted, all six widgets loaded, including the deferred widget data) and the main thread has been free of long tasks for 500 ms.',
        'Interaction latency is timed from the Playwright input until the change is painted and includes each stack’s default debounce: AlfaKit debounces typed `live()` fields by 150 ms (choices such as selects and toggles refresh at once) and global search by 250 ms; Filament’s global search field debounces by 500 ms and its `live()` fields use Livewire’s `wire:model.live` default.',
        'AlfaKit table rows and repeater items are virtualised, so the DOM holds the visible window of a 500-row table.',
    ],
}

const results = []
const clients = new Map()

try {
    for (const target of candidates) {
        disableDebug(target)

        try {
            caches.prepare(target)
            const client = await signIn(target)
            clients.set(target.name, client)
            const server = await serverInfo(client)

            if (server && target.kind === 'alfakit') {
                // Inertia SSR renders the page body into the first response; client rendering doesn't.
                const probe = await client.request('/admin/benchmark-records?perPage=10')
                server.ssr = probe.text.includes('data-slot="content"')
            }

            meta.targets.push({
                name: target.name,
                label: target.label,
                kind: target.kind,
                url: target.url,
                server,
            })
        } catch (error) {
            if (!target.optional && wantedTargets?.includes(target.name)) throw error

            console.log(`Skipping ${target.label} (${target.url}): ${error.message.split('\n')[0]}`)
            meta.targets.push({
                name: target.name,
                label: target.label,
                kind: target.kind,
                url: target.url,
                skipped: error.message.split('\n')[0],
            })
        }
    }

    const active = candidates.filter((target) => clients.has(target.name))

    if (active.length === 0) throw new Error('No target answered /benchmark/login.')

    console.log(
        `\n${meta.hardware.cpu}, ${meta.hardware.cores} cores, ${meta.hardware.memoryGb} GB, ${meta.hardware.os}; PHP ${meta.hardware.php}, Node ${meta.hardware.node}`,
    )
    console.log(
        `Targets: ${active.map((target) => target.label).join(', ')}; ${WARMUP} warm-up + ${RUNS} runs\n`,
    )

    // Server: per scenario and run, every target in turn (drift on the machine hits all alike).
    if (!flag('no-server')) {
        for (const scenario of scenarios) {
            const requests = new Map()

            for (const target of active) {
                try {
                    requests.set(
                        target.name,
                        await requestsFor(
                            clients.get(target.name),
                            target,
                            scenario,
                            SEARCH_TERM,
                            SEARCH_RESULT,
                        ),
                    )
                } catch (error) {
                    console.log(`${target.label} ${scenario.id}: ${error.message.split('\n')[0]}`)
                    results.push({
                        target: target.name,
                        scenario: scenario.id,
                        error: error.message.split('\n')[0],
                    })
                }
            }

            const samples = new Map(
                [...requests.keys()].map((name) => [
                    name,
                    { page: [], interaction: [], deferred: [] },
                ]),
            )

            for (let run = -WARMUP; run < RUNS; run++) {
                for (const [name, request] of requests) {
                    for (const kind of ['page', 'interaction', 'deferred']) {
                        if (!request[kind]) continue

                        const response = await request[kind]()

                        if (run >= 0) samples.get(name)[kind].push(response)
                    }
                }
            }

            for (const [name, sample] of samples) {
                const pick = (kind) =>
                    sample[kind].length === 0
                        ? null
                        : {
                              ttfb: summarize(sample[kind].map((response) => response.ttfb)),
                              total: summarize(sample[kind].map((response) => response.total)),
                              bytes: summarize(sample[kind].map((response) => response.bytes)),
                              gzipBytes: summarize(
                                  sample[kind].map((response) => response.gzipBytes),
                              ),
                          }
                const entry = {
                    target: name,
                    scenario: scenario.id,
                    server: {
                        page: pick('page'),
                        interaction: pick('interaction'),
                        deferred: pick('deferred'),
                    },
                }

                if (requests.get(name).interactionRequestBytes)
                    entry.server.interactionRequestBytes =
                        requests.get(name).interactionRequestBytes

                results.push(entry)
                console.log(
                    `server  ${name.padEnd(9)} ${scenario.id.padEnd(10)} page ttfb ${String(entry.server.page.ttfb.median).padStart(7)} ms ${String(Math.round(entry.server.page.bytes.median / 1024)).padStart(6)} KB` +
                        (entry.server.interaction
                            ? `   interaction ${String(entry.server.interaction.total.median).padStart(7)} ms`
                            : '') +
                        (entry.server.deferred
                            ? `   widget data ${String(entry.server.deferred.total.median).padStart(7)} ms`
                            : ''),
                )
            }
        }
    }

    // Browser: Chrome via Playwright; per scenario and run, every target in turn.
    if (!flag('no-browser')) {
        const browser = await launchBrowser(root)
        meta.browser = `Chrome ${await browserVersion(browser)} (headless, 1440×900, Playwright)`
        const contexts = new Map()

        try {
            for (const target of active)
                contexts.set(target.name, await signedInContext(browser, target))

            for (const scenario of scenarios) {
                const samples = new Map(
                    active.map((target) => [target.name, { loads: [], interactions: [] }]),
                )
                const failed = new Set()
                // A sample that fails (a timeout, a page that never became ready) is retried; a
                // target that fails three times in a scenario is reported as failed.
                const errors = new Map(active.map((target) => [target.name, 0]))

                for (let run = -WARMUP; run < RUNS; run++) {
                    for (const target of active) {
                        if (failed.has(target.name)) continue

                        const selectors = SELECTORS[target.kind]
                        let done = false

                        while (!done && !failed.has(target.name)) {
                            let page = null

                            try {
                                const loaded = await measurePageLoad(
                                    contexts.get(target.name),
                                    target,
                                    scenario,
                                    selectors,
                                )
                                page = loaded.page
                                const latency = scenario.interaction
                                    ? await measureInteraction(
                                          page,
                                          scenario.interaction,
                                          selectors,
                                          SEARCH_TERM,
                                          SEARCH_RESULT,
                                      )
                                    : null

                                if (run >= 0) {
                                    samples.get(target.name).loads.push(loaded.metrics)
                                    samples.get(target.name).interactions.push(latency)
                                }

                                done = true
                            } catch (error) {
                                errors.set(target.name, errors.get(target.name) + 1)
                                console.log(
                                    `browser ${target.name} ${scenario.id}: ${error.message.split('\n')[0]}`,
                                )

                                if (errors.get(target.name) >= 3) failed.add(target.name)
                            } finally {
                                await page?.close()
                            }
                        }
                    }
                }

                for (const target of active) {
                    let entry = results.find(
                        (r) => r.target === target.name && r.scenario === scenario.id,
                    )

                    if (!entry) {
                        entry = { target: target.name, scenario: scenario.id }
                        results.push(entry)
                    }

                    if (failed.has(target.name)) {
                        entry.browserError = 'failed, see the console output'

                        continue
                    }

                    const { loads, interactions } = samples.get(target.name)
                    entry.browserRetries = errors.get(target.name)
                    const metric = (key) => summarize(loads.map((load) => load[key]))

                    entry.browser = {
                        ttfb: metric('ttfb'),
                        domContentLoaded: metric('domContentLoaded'),
                        load: metric('load'),
                        fcp: metric('fcp'),
                        lcp: metric('lcp'),
                        ready: metric('ready'),
                        tti: metric('tti'),
                        totalBlockingTime: metric('totalBlockingTime'),
                        longTasks: metric('longTasks'),
                        domNodes: metric('domNodes'),
                        jsHeap: metric('jsHeap'),
                        transferBytes: metric('transferBytes'),
                        requests: metric('requests'),
                        interaction: summarize(interactions),
                    }

                    console.log(
                        `browser ${target.name.padEnd(9)} ${scenario.id.padEnd(10)} tti ${String(entry.browser.tti?.median).padStart(7)} ms  tbt ${String(entry.browser.totalBlockingTime?.median).padStart(6)} ms  nodes ${String(entry.browser.domNodes?.median).padStart(7)}` +
                            (entry.browser.interaction
                                ? `   interaction ${String(entry.browser.interaction.median).padStart(7)} ms`
                                : ''),
                    )
                }
            }
        } finally {
            await browser.close()
        }
    }
} finally {
    caches.restore()
    restoreEnv()
}

// ------------------------------------------------------------------ Output

mkdirSync(resultsDir, { recursive: true })
meta.loadAverage.end = os.loadavg().map((value) => Math.round(value * 100) / 100)
meta.durationSeconds = Math.round((Date.now() - Date.parse(meta.date)) / 1000)
meta.file = `${meta.date.slice(0, 10)}-${LABEL}.json`
const output = { meta, results }
const json = `${JSON.stringify(output, null, 2)}\n`
writeFileSync(join(resultsDir, meta.file), json)
writeFileSync(join(resultsDir, 'latest.json'), json)
writeFileSync(join(resultsDir, 'latest.md'), fullMarkdown(output))
console.log(`\nWrote benchmarks/results/suite/${meta.file}, latest.json and latest.md\n`)
console.log(fullMarkdown(output))

if (flag('update-docs')) writeDocs(output)
