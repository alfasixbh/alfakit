#!/usr/bin/env node
/**
 * Writes `packages/alfakit/resources/icons/lucide.php`: every Lucide icon name the renderers
 * can draw, with its alias names as search keywords. The IconPicker searches it on the
 * server, so the browser never downloads the list.
 *
 *   node scripts/lucide-icon-names.mjs
 *
 * Run it after upgrading `lucide-react` / `@lucide/vue` / `@lucide/svelte`.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const lucide = join(root, 'packages/react/node_modules/lucide-react')
const source = readFileSync(join(lucide, 'dist/esm/dynamicIconImports.mjs'), 'utf8')
const version = JSON.parse(readFileSync(join(lucide, 'package.json'), 'utf8')).version

/** @type {Map<string, string[]>} canonical name → aliases */
const icons = new Map()

for (const [, name, file] of source.matchAll(
    /"([a-z0-9-]+)": \(\) => import\('\.\/icons\/([a-z0-9-]+)\.mjs'\)/g,
)) {
    if (!icons.has(file)) icons.set(file, [])
    if (name !== file) icons.get(file).push(name)
}

const lines = [...icons.keys()]
    .sort()
    .map((name) => `    '${name}' => '${icons.get(name).join(' ')}',`)

writeFileSync(
    join(root, 'packages/alfakit/resources/icons/lucide.php'),
    `<?php

declare(strict_types=1);

// Generated by scripts/lucide-icon-names.mjs from lucide-react ${version}: icon name => alias names.

return [
${lines.join('\n')}
];
`,
)

console.log(`Wrote ${icons.size} Lucide icons (lucide-react ${version}).`)
